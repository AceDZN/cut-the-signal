import type { Command, Level, Room } from "./model";
type Deck = [string, string, number, number, number | null];
type Link = [string, string, boolean?];
function wreck(
  id: string,
  name: string,
  bufferLimit: number,
  quota: number,
  briefing: string,
  decks: Deck[],
  links: Link[],
  wires: string[][],
  programs: Command[][],
  hint: string[],
): Level {
  const rooms: Room[] = decks.map(([id, label, x, y, value]) => ({
    id,
    label,
    x,
    y,
    relay: value !== null,
    salvageValue: value ?? 0,
  }));
  const failure: Command[][] = [];
  for (const program of programs) {
    const cut = program.indexOf("salvage");
    failure.push(cut < 0 ? program : program.slice(0, cut + 1));
    if (cut >= 0) break;
  }
  return {
    id,
    name,
    dock: "dock",
    bufferLimit,
    quota,
    rooms,
    corridors: links.map(([from, to, oneWay = false]) => ({
      from,
      to,
      oneWay,
    })),
    wires,
    witnessPrograms: programs,
    witnessValue: rooms.reduce((sum, r) => sum + r.salvageValue, 0),
    intendedFailurePrograms: failure,
    briefing,
    teachingPoint: briefing,
    hint,
  };
}
